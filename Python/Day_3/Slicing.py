sentence = "This is a python code"

print(f'Sentence is : {sentence}')

print(f'Slicing  : {sentence[0:11]}')

print(f'Step - even position : {sentence[0:11:2]}')

print(f'Step - 3rd position : {sentence[0:11:3]}')

print(f'Reversing using negative index')

print(f'Reversed {sentence} is : {sentence[::-1]}')

print(f'Slicing using negative index')

print(f'Sliced {sentence} is : {sentence[-1:-14:-1]}')