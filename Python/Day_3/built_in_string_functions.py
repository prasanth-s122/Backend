sentence = "This is a python code"

print(f'Sentence is : {sentence}')

print(f'Upper case : {sentence.upper()}')

print(f'Lower case : {sentence.lower()}')

print(f'Title case : {sentence.title()}')

sentence_2 = "              This is a sentence            "
print(f'Sentence 2 is : {sentence_2}')

print(f'Strip : {sentence_2.strip()}')

print(f' Right Strip : {sentence_2.rstrip()}')

print(f'Left Strip : {sentence_2.lstrip()}')